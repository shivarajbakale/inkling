// Measures the handwriting fonts once, in a real browser, and writes
// src/core/metrics.generated.ts. Layout then never needs a canvas or loaded
// fonts, so it is the same in every browser, in tests and in Node.
//
//   node scripts/font-metrics.mjs
//
// Needs Playwright (any project's copy works: PLAYWRIGHT_FROM=/path/to/project).
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const from = process.env.PLAYWRIGHT_FROM ?? process.cwd() + '/';
const { chromium } = createRequire(from)('playwright');

const HANDS = {
  Caveat: [500, 700],
  Kalam: [400, 600],
  'Patrick Hand': [400, 600],
  'Gochi Hand': [400, 600],
  'Architects Daughter': [400, 600],
};
const FONT_CSS =
  'https://fonts.googleapis.com/css2?family=Caveat:wght@400..700&family=Kalam:wght@400;700&family=Patrick+Hand&family=Gochi+Hand&family=Architects+Daughter&display=swap';

const chars = [];
for (let c = 32; c <= 126; c++) chars.push(String.fromCharCode(c));
for (let c = 160; c <= 255; c++) chars.push(String.fromCharCode(c));
chars.push(...'–—‘’“”•…→←↑↓✓✗€£×÷≈≠≤≥°'.split(''));

const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL ?? 'chrome' });
const page = await browser.newPage();
await page.setContent(`<link rel="stylesheet" href="${FONT_CSS}">`);
await page.waitForLoadState('networkidle');

const result = await page.evaluate(
  async ({ hands, chars }) => {
    const out = {};
    const ctx = document.createElement('canvas').getContext('2d');
    for (const [family, weights] of Object.entries(hands)) {
      out[family] = {};
      for (const w of weights) {
        await document.fonts.load(`${w} 100px '${family}'`);
        if (!document.fonts.check(`${w} 100px '${family}'`)) throw new Error(`font did not load: ${family} ${w}`);
        ctx.font = `${w} 100px '${family}', cursive`;
        const widths = {};
        for (const ch of chars) widths[ch] = Math.round(ctx.measureText(ch).width * 10) / 10;
        const m = ctx.measureText('Hxgy');
        out[family][w] = {
          widths,
          ascent: Math.round(m.fontBoundingBoxAscent * 10) / 10,
          descent: Math.round(m.fontBoundingBoxDescent * 10) / 10,
        };
      }
    }
    return out;
  },
  { hands: HANDS, chars },
);
await browser.close();

// Store widths as one string of characters plus a parallel array, which is
// compact and keeps the generated file readable in diffs.
let ts = `// Generated by scripts/font-metrics.mjs — do not edit by hand.
// Advance widths at 100px, per font family and weight.

export interface FaceMetrics { chars: string; widths: number[]; ascent: number; descent: number }

export const METRICS: Record<string, Record<number, FaceMetrics>> = {\n`;
for (const [family, byWeight] of Object.entries(result)) {
  ts += `  ${JSON.stringify(family)}: {\n`;
  for (const [w, m] of Object.entries(byWeight)) {
    const cs = Object.keys(m.widths).join('');
    ts += `    ${w}: {\n      chars: ${JSON.stringify(cs)},\n      widths: [${Object.values(m.widths).join(', ')}],\n      ascent: ${m.ascent},\n      descent: ${m.descent},\n    },\n`;
  }
  ts += `  },\n`;
}
ts += `};\n`;
writeFileSync('src/core/metrics.generated.ts', ts);
console.log('wrote src/core/metrics.generated.ts', ts.length, 'bytes');
